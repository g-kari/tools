const FONT_MAP: Record<AsciiFont, Record<string, string[]>> = {
  standard: STANDARD,
  block: BLOCK,
  banner: BANNER,
  dots: DOTS,
  thin: THIN,
};

/**
 * フォントの行数を返す
 * @param font フォントキー
 * @returns 行数
 */
export function getFontLineCount(font: AsciiFont): number {
  if (font === "banner") return 7;
  return 5;
}

/**
 * テキストをASCIIアートに変換する
 * @param text 入力テキスト
 * @param font 使用するフォント
 * @returns ASCIIアートの結果
 */
export function generateAsciiArt(text: string, font: AsciiFont): AsciiArtResult {
  if (!text || text.trim() === "") {
    return { text: "", lineCount: 0, charCount: 0 };
  }

  const fontData = FONT_MAP[font];
  const lineCount = getFontLineCount(font);

  // テキストを大文字に変換（フォントは大文字のみ定義）
  const upperText = text.toUpperCase();

  // 行ごとに文字パターンを結合
  const lines: string[] = Array.from({ length: lineCount }, () => "");

  for (const char of upperText) {
    const pattern = fontData[char] || fontData[" "] || Array(lineCount).fill(" ");
    const charLines = pattern.length === lineCount ? pattern : Array(lineCount).fill(" ");

    for (let i = 0; i < lineCount; i++) {
      lines[i] += (lines[i].length > 0 ? " " : "") + (charLines[i] ?? " ");
    }
  }

  const result = lines.join("\n");
  return {
    text: result,
    lineCount: lines.length,
    charCount: result.length,
  };
}

/**
 * テキストが変換可能かどうかを確認する
 * @param text 入力テキスト
 * @returns 変換可能な場合true
 */
export function isConvertible(text: string): boolean {
  return text.trim().length > 0 && text.length <= 20;
}
